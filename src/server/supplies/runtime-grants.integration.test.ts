// @vitest-environment node
import { randomUUID } from "node:crypto";
import { Pool } from "pg";
import { afterAll, describe, expect, it } from "vitest";
import { buildRuntimeGrantStatements, runtimeInventorySql } from "../../../scripts/database-runtime-role-security";

const databaseUrl = process.env.TEST_DATABASE_URL;
const pool = databaseUrl ? new Pool({ connectionString: databaseUrl }) : null;
const mutable = ["supplies_settings", "supplies_categories", "supplies_products", "supplies_variants", "supplies_images", "supplies_stock_reservations"];
const appendOnly = ["supplies_audit_logs", "supplies_order_items"];
afterAll(async () => { await pool?.end(); });

describe.skipIf(!databaseUrl)("Supplies table ACLs on an owned disposable database", () => {
  it("allows catalogue SIU and snapshot/audit SI, denies destructive grants, and detects missing required old/new UPDATE grants", async () => {
    const databaseName = decodeURIComponent(new URL(databaseUrl!).pathname.slice(1));
    if (!/^rnr_gallery_test_release_gate_[a-f0-9]{8}_[a-z0-9_]{6,12}_integration$/.test(databaseName)) {
      throw new Error("Runtime grant acceptance requires a session-specific release-gate disposable database.");
    }
    const roleName = `rnr_test_supplies_${randomUUID().replaceAll("-", "")}`;
    const quotedRole = `"${roleName}"`;
    const owner = await pool!.query<{ role: string }>("select current_user as role");
    const migrationRole = owner.rows[0].role;
    let created = false;
    try {
      await pool!.query(`CREATE ROLE ${quotedRole} NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS`);
      created = true;
      // Use canonical table grants only. Do not invoke the manager or change PUBLIC/function/default privileges.
      for (const statement of buildRuntimeGrantStatements({ databaseName, schemaName: "public", runtimeRole: roleName, migrationRole })) {
        if (statement.includes("FROM PUBLIC") || statement.includes("FUNCTION") || statement.startsWith("ALTER DEFAULT PRIVILEGES") || statement.includes("SEQUENCES")) continue;
        await pool!.query(statement);
      }
      for (const table of [...mutable, ...appendOnly]) {
        const result = await pool!.query<{ select: boolean; insert: boolean; update: boolean; delete: boolean; truncate: boolean }>(
          "select has_table_privilege($1, $2, 'SELECT') as select, has_table_privilege($1, $2, 'INSERT') as insert, has_table_privilege($1, $2, 'UPDATE') as update, has_table_privilege($1, $2, 'DELETE') as delete, has_table_privilege($1, $2, 'TRUNCATE') as truncate",
          [roleName, `public.${table}`],
        );
        expect(result.rows[0], table).toEqual({ select: true, insert: true, update: mutable.includes(table), delete: false, truncate: false });
      }
      const legacy = await pool!.query<{ allowed: boolean }>("select has_table_privilege($1, 'public.orders', 'SELECT') and has_table_privilege($1, 'public.orders', 'INSERT') and has_table_privilege($1, 'public.orders', 'UPDATE') and has_table_privilege($1, 'public.orders', 'DELETE') as allowed", [roleName]);
      expect(legacy.rows[0].allowed).toBe(true);
      const inventory = () => pool!.query<{ missing_public_table_privileges: number; unexpected_public_table_privileges: number }>(runtimeInventorySql(), [roleName, migrationRole]);
      expect((await inventory()).rows[0]).toMatchObject({ missing_public_table_privileges: 0, unexpected_public_table_privileges: 0 });
      for (const table of ["supplies_products", "orders"]) {
        await pool!.query(`REVOKE UPDATE ON TABLE "public"."${table}" FROM ${quotedRole}`);
        expect((await inventory()).rows[0].missing_public_table_privileges).toBe(1);
        await pool!.query(`GRANT UPDATE ON TABLE "public"."${table}" TO ${quotedRole}`);
      }
      const client = await pool!.connect();
      try {
        for (const statement of ["DELETE FROM supplies_products WHERE false", "UPDATE supplies_audit_logs SET action = action WHERE false", "UPDATE supplies_order_items SET quantity = quantity WHERE false"]) {
          await client.query("BEGIN");
          try {
            await client.query(`SET LOCAL ROLE ${quotedRole}`);
            await expect(client.query(statement)).rejects.toMatchObject({ code: "42501" });
          } finally { await client.query("ROLLBACK"); }
        }
      } finally { client.release(); }
    } finally {
      if (created) {
        // This role is generated by this fixture and owns no objects; revoke only its owned-database grants.
        await pool!.query(`REVOKE ALL PRIVILEGES ON ALL TABLES IN SCHEMA "public" FROM ${quotedRole}`);
        await pool!.query(`REVOKE ALL PRIVILEGES ON SCHEMA "public" FROM ${quotedRole}`);
        await pool!.query(`REVOKE ALL PRIVILEGES ON DATABASE "${databaseName}" FROM ${quotedRole}`);
        await pool!.query(`DROP ROLE ${quotedRole}`);
      }
    }
  });
});
